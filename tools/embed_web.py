#!/usr/bin/env python3
"""Turn web/index.html into a gzipped byte array the firmware serves.

Usage: embed_web.py web/index.html firmware/brain/web_ui.h
"""
import gzip
import sys


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, "rb") as f:
        raw = f.read()
    # mtime=0 keeps the output identical from run to run.
    packed = gzip.compress(raw, compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(packed), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in packed[i:i + 16]) + ",")
    with open(dst, "w") as f:
        f.write("// Generated by tools/embed_web.py from web/index.html. Do not edit.\n")
        f.write("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n")
        f.write(f"const size_t WEB_UI_GZ_LEN = {len(packed)};\n")
        f.write("const uint8_t WEB_UI_GZ[] PROGMEM = {\n")
        f.write("\n".join(rows))
        f.write("\n};\n")
    print(f"{src}: {len(raw)} bytes -> {len(packed)} bytes gzipped -> {dst}")


if __name__ == "__main__":
    main()
